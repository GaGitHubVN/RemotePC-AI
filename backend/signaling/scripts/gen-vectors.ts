// Generates deterministic cross-language test vectors into packages/protocol/vectors/v1.json.
// C# (RemotePC.Core.Tests) and Dart (mobile test/) implementations must reproduce every value.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { deviceId, edSign, keysFromSeeds } from '../src/protocol/crypto.ts';
import { b64u, fromB64u, utf8 } from '../src/protocol/encoding.ts';
import { envelopeKey, pairProof, pairTranscript, sealEnvelope, verifyCode } from '../src/protocol/envelope.ts';

const seed = (byte: number) => new Uint8Array(32).fill(byte);
const host = keysFromSeeds(seed(0x11), seed(0x22));
const client = keysFromSeeds(seed(0x33), seed(0x44));
const hostId = deviceId(host.edPk);
const clientId = deviceId(client.edPk);

const nonce = 'AAECAwQFBgcICQoLDA0ODxAREhMUFRYXGBkaGxwdHh8';
const helloMsg = `remotepc-signal-v1\n${nonce}\n${hostId}\nhost`;

const key = envelopeKey(client.xSk, host.xPk, clientId, hostId);
const env = sealEnvelope(
  key,
  { typ: 'session.open', from: clientId, to: hostId, sid: '', seq: 7, ts: 1763630000000, n: 'AAAAAAAAAAAAAAAA' },
  { reqId: 'r1', text: 'Xin chào 👋' },
);
const pairEnv = sealEnvelope(
  key,
  {
    typ: 'pair.request',
    from: clientId,
    to: hostId,
    sid: '',
    seq: 1,
    ts: 1763630000000,
    n: 'AQEBAQEBAQEBAQEB',
    kx: { edPk: b64u(client.edPk), xPk: b64u(client.xPk) },
  },
  { pairNonce: 'nonce-1' },
);

const t = {
  hostId,
  clientId,
  clientEdPk: b64u(client.edPk),
  clientXPk: b64u(client.xPk),
  hostEdPk: b64u(host.edPk),
  hostXPk: b64u(host.xPk),
  pairNonce: 'pn-0001',
};
const transcript = pairTranscript(t);
const qrSecret = seed(0x55);

const vectors = {
  version: 1,
  note: 'Generated by backend/signaling/scripts/gen-vectors.ts — do not edit by hand.',
  keys: {
    host: { edSeed: b64u(seed(0x11)), xSk: b64u(seed(0x22)), edPk: b64u(host.edPk), xPk: b64u(host.xPk), id: hostId },
    client: { edSeed: b64u(seed(0x33)), xSk: b64u(seed(0x44)), edPk: b64u(client.edPk), xPk: b64u(client.xPk), id: clientId },
  },
  hello: { nonce, role: 'host', message: helloMsg, sig: b64u(edSign(host.edSk, utf8(helloMsg))) },
  envelope: {
    key: b64u(key),
    payload: { reqId: 'r1', text: 'Xin chào 👋' },
    sealed: env,
    pairRequest: pairEnv,
  },
  pairing: {
    ...t,
    transcript: new TextDecoder().decode(transcript),
    qrSecret: b64u(qrSecret),
    qrProof: b64u(pairProof(qrSecret, transcript)),
    code: 'K7MXQ2RTP9',
    codeProof: b64u(pairProof(utf8('K7MXQ2RTP9'), transcript)),
    verifyCode: verifyCode(transcript),
  },
};

const out = fileURLToPath(new URL('../../../packages/protocol/vectors/v1.json', import.meta.url));
writeFileSync(out, JSON.stringify(vectors, null, 2) + '\n');
console.log(`wrote ${out}`);
void fromB64u; // keep import list honest for readers
